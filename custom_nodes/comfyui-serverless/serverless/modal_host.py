def validate_modal_setup() -> Dict[str, Any]:
    """
    Validate Modal setup and return status.
    
    Returns:
        Dictionary with validation results
    """
    results = {
        'modal_installed': False,
        'modal_authenticated': False,
        'errors': []
    }
    
    try:
        import modal
        results['modal_installed'] = True
        
        # Try to check authentication
        try:
            # This will fail if not authenticated
            modal.app.App.from_name("test", create_if_missing=False)
            results['modal_authenticated'] = True
        except Exception:
            results['errors'].append("Modal not authenticated. Run 'modal token new'")
    except ImportError:
        results['errors'].append("Modal SDK not installed. Install with: pip install modal")
    
    return results

