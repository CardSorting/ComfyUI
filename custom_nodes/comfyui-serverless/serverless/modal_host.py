def get_modal_comfyui_config(
    models_volume_name: str = "comfyui-models",
    outputs_volume_name: str = "comfyui-outputs",
    gpu_config: str = "A10G",
    timeout: int = 600,
    scaledown_window: int = 300
) -> Dict[str, Any]:
    """
    Get configuration for Modal ComfyUI deployment.
    
    Args:
        models_volume_name: Name of the Modal volume for models
        outputs_volume_name: Name of the Modal volume for outputs
        gpu_config: GPU configuration (e.g., "A10G", "T4")
        timeout: Function execution timeout in seconds
        scaledown_window: Container idle time before scaling down (seconds)
    
    Returns:
        Dictionary with Modal configuration
    """
    return {
        'models_volume_name': models_volume_name,
        'outputs_volume_name': outputs_volume_name,
        'gpu_config': gpu_config,
        'timeout': timeout,
        'scaledown_window': scaledown_window,
        'headless': True,
    }


